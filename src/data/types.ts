export type CategoryId = string;

/**
 * The single source of truth for the catalogue's shape.
 *
 * Two layers, deliberately kept apart:
 *  - `repo`      — machine facts imported from GitHub (stars, license, pushed_at...).
 *                  Never edited by hand, always carries `fetchedAt`.
 *  - editorial   — Chinese copy written by a human after reading the README.
 *                  Every claim must point at something in the repository.
 *
 * Absent data is `null` + an explicit `note`, never a made-up number. The UI renders
 * `未知` for those, so a missing star count stays missing instead of becoming 0.
 */

export interface Category {
  id: CategoryId;
  name: string;
  english: string;
  blurb: string;
  /** A short editorial line used on the category page. */
  intro: string;
}

export type Sourced = 'api' | 'manual';
export type Enrichment = 'api' | 'manual' | 'scraped' | 'unknown';
export type ProjectStatus = 'active' | 'stale' | 'archived' | 'unknown' | 'dead';

export interface License {
  /** SPDX id as reported by GitHub, or null when the repo has no detectable license. */
  spdx: string | null;
  name: string | null;
  /** Why it is unknown / what to check, shown verbatim in the UI. */
  note?: string;
  url?: string | null;
}

export interface RepoMeta {
  owner: string | null;
  name: string | null;
  fullName: string | null;
  url: string | null;
  homepage: string | null;
  description: string | null;
  stars: number | null;
  forks: number | null;
  openIssues: number | null;
  language: string | null;
  topics: string[];
  license: License;
  createdAt: string | null;
  pushedAt: string | null;
  archived: boolean | null;
  /** When this snapshot was taken from the GitHub API. */
  fetchedAt: string | null;
  source: Sourced;
  /** Non-fatal import problems ("README 读取失败"), surfaced in the admin panel. */
  warnings?: string[];
}

export interface ReadmeDigest {
  path: string | null;
  /** First heading / first meaningful paragraph, verbatim, trimmed to a sane length. */
  excerpt: string | null;
  /** Headings found in the README, used to ground the "主要功能" section. */
  headings: string[];
  /** Plain-text length after stripping markup — a proxy for "how much was actually read". */
  chars: number;
  fetchedAt: string | null;
  truncated: boolean;
}

export interface Screenshot {
  src: string;
  /** 880px-wide variant used in grids and cards. */
  card?: string;
  alt: string;
  /** Where it came from: the live site, the repo's social preview, or an owned placeholder. */
  origin: 'live' | 'og' | 'placeholder';
  capturedAt: string | null;
  credit?: string;
  /** True when the image is generated by us, not a screenshot of the product. */
  synthetic?: boolean;
}

export interface Feature {
  title: string;
  detail: string;
}

export interface SetupStep {
  title: string;
  detail: string;
}

export interface Setup {
  /** 零门槛 / 低门槛 / 中等门槛 / 较高门槛 / 高门槛 */
  effort: string;
  /** One sentence: what it costs to try (account? Docker? local install?). */
  effortNote: string;
  requires: string[];
  steps: SetupStep[];
  /** Does it need an API key / paid account / GPU? */
  cost: string;
}

export interface Project {
  slug: string;
  name: string;
  /** One-liner shown on cards. Max ~34 CJK chars. */
  tagline: string;
  /** 2–4 sentence overview on the detail page. */
  summary: string;
  category: CategoryId;
  /** Resolved display name, denormalised at build time. */
  categoryName?: string;
  tags: string[];
  aliases?: string[];
  /** Who it is for, one short phrase (used by the audience filter). */
  audience: string;
  /** 2–4 bullet points: "如果你是……" */
  audienceFor: string[];
  features: Feature[];
  /** Truthful description of how the Chinese copy was produced. */
  contentBasis: string;
  setup: Setup;
  license: License;
  repo: RepoMeta;
  officialUrl: string | null;
  demoUrl: string | null;
  /** null = no good live URL, do not invent one. */
  linkStatus: 'ok' | 'unchecked' | 'dead';
  linkCheckedAt: string | null;
  screenshots: Screenshot[];
  readme: ReadmeDigest;
  /** Editorial flags. */
  featured: boolean;
  editorsNote?: string;
  /** ISO date the project entered the catalogue. */
  addedAt: string;
  updatedAt: string;
  /** Yesterday's / this week's numbers that we can actually compute from our own data. */
  popularityScore: number;
  weeklyScore: number;
  review: {
    status: 'published' | 'draft' | 'needs-review';
    /** Who produced the Chinese copy: a person, or the automatic pipeline. */
    mode?: 'human' | 'auto';
    reviewedBy: string | null;
    reviewedAt: string | null;
    /** What a reviewer should double-check next time. */
    todo?: string;
  };
}
